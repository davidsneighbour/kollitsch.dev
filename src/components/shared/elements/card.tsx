import { cn } from '@utils/shadcn-utils';
import * as React from 'react';

function Card({ className, ...props }: React.ComponentProps<'div'>) {
  return (
    <div
      data-slot="card"
      className={cn(
        // DESIGN.md Cards: rounded-lg (not rounded-xl, that's reserved for
        // images inside cards), shadow-sm in light mode only, outline
        // instead of shadow in dark mode - see "Elevation & Depth".
        'flex flex-col gap-6 rounded-lg border-0 bg-card py-6 text-card-foreground shadow-sm',
        'dark:bg-card/50 dark:shadow-none dark:outline dark:-outline-offset-1 dark:outline-white/10',
        className,
      )}
      {...props}
    />
  );
}

